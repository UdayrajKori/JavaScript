
// Assignment Operators

let a = 10;
let b = 5;

a += b; // a = a + b
console.log("After a += b, a = ", a);

a -= b; // a = a - b
console.log("After a -= b, a = ", a);

a *= b; // a = a * b
console.log("After a *= b, a = ", a);

a /= b; // a = a / b
console.log("After a /= b, a = ", a);

a %= b; // a = a % b
console.log("After a %= b, a = ", a);
