let a = prompt("Enter first number: ");
let b = prompt("Enter second number: ");

 a = Number(a);
 b = Number(b);

 let sum = a + b;
 let sub = a - b;
 let mul = a * b;
 let div = a / b;
 let mod = a % b;

 console.log(`The sum of ${a} and ${b} is: ${sum}`);
 console.log(`The difference when ${b} is subtracted from ${a} is: ${sub}`);
 console.log(`The product of ${a} and ${b} is: ${mul}`);
 console.log(`The quotient when ${a} is divided by ${b} is: ${div}`);
 console.log(`The remainder when ${a} is divided by ${b} is: ${mod}`);















